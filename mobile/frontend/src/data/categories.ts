export const getCategoryMeta = (key: string, source: CategoryMeta[] = categories): CategoryMeta => {
  const found = source.find((c) => c.key === key);
  if (found) return found;
  return {
    key,
    label: key
      .split('-')
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join(' '),
    icon: 'briefcase-outline',
    color: colors.categoryMore,
    kycDocumentLabel: 'Work Document',
  };
};
